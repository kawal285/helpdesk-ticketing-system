/*
 * Knowledge-gap topic grouping evaluation.
 *
 *   node scripts/ai/evaluate-gap-grouping.js
 *
 * Embeds the hand-labelled questions in tests/similarity/gap-questions.json
 * with the real embedding model and groups them exactly as the
 * knowledge-gap report does (knowledgeGapService.groupByTopic), at a range
 * of thresholds. For every pair of questions it checks whether they ended
 * up together and whether they really are the same topic:
 *
 *   pair precision: of the pairs put together, how many really match
 *   pair recall:    of the pairs that really match, how many were put together
 *
 * Writes docs/knowledge-gap-grouping-evaluation.md (overwritten each run).
 */

require('dotenv').config({ quiet: true });

const fs = require('fs');
const path = require('path');

const { embedDocuments, getModelInfo } = require('../../src/services/rag/embeddingService');
const { groupByTopic, DEFAULT_GROUP_THRESHOLD } = require('../../src/services/knowledgeGapService');
const questions = require('../../tests/similarity/gap-questions.json');

const f = (n) => n.toFixed(3);

function scoreGrouping(items, topics) {
  const groupOf = new Map();
  topics.forEach((topic, i) => topic.items.forEach((item) => groupOf.set(item.index, i)));

  let tp = 0;
  let fp = 0;
  let fn = 0;
  for (let i = 0; i < items.length; i += 1) {
    for (let j = i + 1; j < items.length; j += 1) {
      const together = groupOf.get(i) === groupOf.get(j);
      const same = items[i].topic === items[j].topic;
      if (together && same) tp += 1;
      else if (together && !same) fp += 1;
      else if (!together && same) fn += 1;
    }
  }
  const precision = tp + fp ? tp / (tp + fp) : 1;
  const recall = tp + fn ? tp / (tp + fn) : 1;
  const f1 = precision + recall ? (2 * precision * recall) / (precision + recall) : 0;
  return { topics: topics.length, tp, fp, fn, precision, recall, f1 };
}

async function run() {
  const realTopics = new Set(questions.map((q) => q.topic)).size;
  console.log(`Grouping ${questions.length} questions (${realTopics} real topics) with ${getModelInfo().name}...`);

  const vectors = await embedDocuments(questions.map((q) => q.q));
  const items = questions.map((q, index) => ({ ...q, index, vector: vectors[index] }));

  const thresholds = [];
  for (let t = 0.55; t <= 0.801; t += 0.01) thresholds.push(Number(t.toFixed(2)));
  const sweep = thresholds.map((t) => ({ threshold: t, ...scoreGrouping(items, groupByTopic(items, t)) }));

  const chosenTopics = groupByTopic(items, DEFAULT_GROUP_THRESHOLD);
  const chosen = scoreGrouping(items, chosenTopics);
  console.log(
    `At ${DEFAULT_GROUP_THRESHOLD}: ${chosen.topics} topics (real ${realTopics}), ` +
      `pair precision ${f(chosen.precision)}, recall ${f(chosen.recall)}, F1 ${f(chosen.f1)}`
  );

  const md = [
    '# Knowledge-gap topic grouping: evaluation',
    '',
    `Generated by \`node scripts/ai/evaluate-gap-grouping.js\` on ${new Date().toISOString()} ` +
      `with \`${getModelInfo().name}\`. Overwritten on every run.`,
    '',
    `${questions.length} hand-labelled questions in ${realTopics} topics ` +
      '(tests/similarity/gap-questions.json), grouped the same way as the report.',
    '',
    '- **Pair precision**: of the question pairs put in the same topic, how many really are the same topic.',
    '- **Pair recall**: of the pairs that really are the same topic, how many were put together.',
    '',
    '## Threshold sweep',
    '',
    `| Threshold | Topics found (real: ${realTopics}) | Right pairs | Wrong pairs | Missed pairs | Precision | Recall | F1 |`,
    '| --- | --- | --- | --- | --- | --- | --- | --- |',
    ...sweep.map((s) => {
      const mark = s.threshold === DEFAULT_GROUP_THRESHOLD ? ' **(used)**' : '';
      return `| ${s.threshold}${mark} | ${s.topics} | ${s.tp} | ${s.fp} | ${s.fn} | ${f(s.precision)} | ${f(s.recall)} | ${f(s.f1)} |`;
    }),
    '',
    `## Topics found at ${DEFAULT_GROUP_THRESHOLD}`,
    '',
    '| Topic | Questions (real topic in brackets) |',
    '| --- | --- |',
    ...chosenTopics.map(
      (topic, i) => `| ${i + 1} | ${topic.items.map((item) => `${item.q} (${item.topic})`).join('<br>')} |`
    ),
    '',
  ].join('\n');

  const out = path.join(__dirname, '..', '..', 'docs', 'knowledge-gap-grouping-evaluation.md');
  fs.writeFileSync(out, md);
  console.log('Written: docs/knowledge-gap-grouping-evaluation.md');
}

run().catch((error) => {
  console.error('Evaluation failed:', error.message);
  process.exitCode = 1;
});
