/*
 * Similar-ticket (duplicate) detection evaluation.
 *
 *   node scripts/ai/evaluate-similar-tickets.js
 *
 * Embeds every pair in tests/similarity/ticket-duplicate-pairs.json with
 * the real embedding model (the one in .env, nomic-embed-text by
 * default), scores them with cosine similarity -- exactly what
 * similarTicketService does -- and works out precision, recall and F1 for
 * "is a duplicate" at a range of thresholds.
 *
 * Writes docs/similar-tickets-evaluation.md (overwritten on every run).
 */

require('dotenv').config({ quiet: true });

const fs = require('fs');
const path = require('path');

const { embedDocuments, getModelInfo } = require('../../src/services/rag/embeddingService');
const { cosineSimilarity } = require('../../src/services/rag/similarity');
const { ticketText, DEFAULT_THRESHOLD } = require('../../src/services/similarTicketService');
const pairs = require('../../tests/similarity/ticket-duplicate-pairs.json');

function asTicket(text) {
  // The pairs are written as one sentence each; treat it as the title.
  return ticketText({ title: text, description: '' });
}

function scoreAt(results, threshold) {
  let tp = 0;
  let fp = 0;
  let fn = 0;
  for (const r of results) {
    const predicted = r.score >= threshold;
    const actual = r.label === 'duplicate';
    if (predicted && actual) tp += 1;
    else if (predicted && !actual) fp += 1;
    else if (!predicted && actual) fn += 1;
  }
  const precision = tp + fp ? tp / (tp + fp) : 0;
  const recall = tp + fn ? tp / (tp + fn) : 0;
  const f1 = precision + recall ? (2 * precision * recall) / (precision + recall) : 0;
  return { threshold, tp, fp, fn, precision, recall, f1 };
}

function stats(values) {
  return {
    min: Math.min(...values),
    max: Math.max(...values),
    avg: values.reduce((a, b) => a + b, 0) / values.length,
  };
}

const f = (n) => n.toFixed(3);

async function run() {
  console.log(`Scoring ${pairs.length} ticket pairs with ${getModelInfo().name}...`);

  const results = [];
  for (const pair of pairs) {
    const [a, b] = await embedDocuments([asTicket(pair.a), asTicket(pair.b)]);
    results.push({ ...pair, score: cosineSimilarity(a, b) });
  }

  const groups = ['duplicate', 'related', 'unrelated'].map((label) => ({
    label,
    count: results.filter((r) => r.label === label).length,
    ...stats(results.filter((r) => r.label === label).map((r) => r.score)),
  }));

  const thresholds = [];
  for (let t = 0.65; t <= 0.851; t += 0.01) thresholds.push(Number(t.toFixed(2)));
  const sweep = thresholds.map((t) => scoreAt(results, t));
  const chosen = scoreAt(results, DEFAULT_THRESHOLD);

  for (const g of groups) {
    console.log(`  ${g.label.padEnd(10)} min ${f(g.min)}  max ${f(g.max)}  avg ${f(g.avg)}`);
  }
  console.log(
    `At ${DEFAULT_THRESHOLD}: precision ${f(chosen.precision)}, recall ${f(chosen.recall)}, F1 ${f(chosen.f1)}`
  );

  const md = [
    '# Similar ticket detection: evaluation',
    '',
    `Generated by \`node scripts/ai/evaluate-similar-tickets.js\` on ${new Date().toISOString()} ` +
      `with \`${getModelInfo().name}\`. Overwritten on every run.`,
    '',
    `${pairs.length} hand-labelled ticket pairs (tests/similarity/ticket-duplicate-pairs.json):`,
    '',
    '- **duplicate**: the same problem written differently (should be suggested)',
    '- **related**: the same area but a different problem, for example "printer jammed" vs "printer out of toner" (should not)',
    '- **unrelated**: different problems (should not)',
    '',
    '## Scores by pair type',
    '',
    '| Pair type | Pairs | Lowest | Highest | Average |',
    '| --- | --- | --- | --- | --- |',
    ...groups.map((g) => `| ${g.label} | ${g.count} | ${f(g.min)} | ${f(g.max)} | ${f(g.avg)} |`),
    '',
    '## Threshold sweep',
    '',
    'A pair is suggested as a duplicate when its score is at or above the threshold.',
    '',
    '| Threshold | Found (of 12) | Wrong suggestions | Missed | Precision | Recall | F1 |',
    '| --- | --- | --- | --- | --- | --- | --- |',
    ...sweep.map((s) => {
      const mark = s.threshold === DEFAULT_THRESHOLD ? ' **(used)**' : '';
      return `| ${s.threshold}${mark} | ${s.tp} | ${s.fp} | ${s.fn} | ${f(s.precision)} | ${f(s.recall)} | ${f(s.f1)} |`;
    }),
    '',
    '## Every pair',
    '',
    '| # | Type | Score | Suggested? | Ticket A | Ticket B |',
    '| --- | --- | --- | --- | --- | --- |',
    ...results.map(
      (r) =>
        `| ${r.id} | ${r.label} | ${f(r.score)} | ${r.score >= DEFAULT_THRESHOLD ? 'yes' : 'no'} | ${r.a} | ${r.b} |`
    ),
    '',
  ].join('\n');

  const out = path.join(__dirname, '..', '..', 'docs', 'similar-tickets-evaluation.md');
  fs.writeFileSync(out, md);
  console.log('Written: docs/similar-tickets-evaluation.md');
}

run().catch((error) => {
  console.error('Evaluation failed:', error.message);
  process.exitCode = 1;
});
