/*
 * Ticket classification evaluation harness.
 *
 *   node scripts/ai/evaluate-classification.js
 *
 * Runs every description in tests/classification/ticket-classification-
 * evaluation-set.json through getAiSuggestions() -- the exact function
 * ticket.controller.js calls on real ticket creation, including its 8s
 * timeout and never-throws guarantee -- and compares the predicted
 * category/priority against the hand-labelled expected values.
 *
 * Mirrors scripts/rag/evaluate-answers.js: a real, live-API run captured
 * to a raw results file, not a Jest test (a real Gemini call per question
 * is slow and depends on external quota/availability, which is exactly
 * the kind of thing that makes a test suite flaky rather than useful).
 *
 * Writes docs/ai-classification-evaluation-raw.json (every prediction) and
 * docs/ai-classification-metrics.md (confusion matrices, precision,
 * recall, F1 and Cohen's kappa for category, priority and P1-P4 level)
 * and docs/ai-handoff-evaluation.md (the "Needs human check" handoff:
 * how many tickets go to a person and whether that was the right call).
 */

require('dotenv').config();

const fs = require('fs');
const path = require('path');

const { getAiSuggestions } = require('../../src/services/aiService');
const { getModelInfo } = require('../../src/services/rag/generationService');
const {
  summariseByField,
  confusionPairs,
  evaluateField,
  handoffSweep,
  NONE,
} = require('./classificationStats');
const { humanCheckReasons, getThresholds } = require('../../src/utils/aiConfidence');
const {
  CATEGORIES,
  PRIORITIES,
  LEVELS,
  priorityLevel,
} = require('../../src/utils/ticketFields');
const testSet = require('../../tests/classification/ticket-classification-evaluation-set.json');

function pct(value) {
  return `${(value * 100).toFixed(1)}%`;
}

function matrixTable(m) {
  const columns = [...m.labels, NONE];
  const used = columns.filter(
    (col) => col !== NONE || m.labels.some((row) => m.matrix[row][NONE] > 0)
  );
  const lines = [
    `| Expected \\ AI | ${used.join(' | ')} |`,
    `| --- | ${used.map(() => '---').join(' | ')} |`,
  ];
  for (const row of m.labels) {
    const cells = used.map((col) =>
      row === col ? `**${m.matrix[row][col]}**` : String(m.matrix[row][col])
    );
    lines.push(`| ${row} | ${cells.join(' | ')} |`);
  }
  return lines.join('\n');
}

function metricsTable(m) {
  const lines = [
    '| Label | Precision | Recall | F1 | Tickets |',
    '| --- | --- | --- | --- | --- |',
  ];
  for (const label of m.labels) {
    const c = m.perClass[label];
    lines.push(`| ${label} | ${c.precision} | ${c.recall} | ${c.f1} | ${c.support} |`);
  }
  lines.push(`| **Macro average** | ${m.macro.precision} | ${m.macro.recall} | ${m.macro.f1} | ${m.total} |`);
  lines.push(`| **Weighted average** | ${m.weighted.precision} | ${m.weighted.recall} | ${m.weighted.f1} | ${m.total} |`);
  return lines.join('\n');
}

function section(title, m) {
  return [
    `## ${title}`,
    '',
    `Accuracy **${pct(m.accuracy)}** (${m.correct}/${m.total}). ` +
      `Cohen's kappa **${m.kappa}** (${m.kappaStrength} agreement).`,
    '',
    'Confusion matrix (rows are the hand labels, columns what the AI said; the diagonal is correct):',
    '',
    matrixTable(m),
    '',
    metricsTable(m),
    '',
  ].join('\n');
}

function metricsReport(metrics, results, generatedAt) {
  const unavailable = results.filter((r) => r.aiUnavailable).length;
  return [
    '# AI classification metrics',
    '',
    `Generated by \`node scripts/ai/evaluate-classification.js\` on ${generatedAt}, ` +
      `model \`${getModelInfo().name}\`, ${results.length} hand-labelled tickets ` +
      '(tests/classification/ticket-classification-evaluation-set.json). ' +
      'This file is overwritten on every run; every prediction is in ai-classification-evaluation-raw.json.',
    '',
    unavailable
      ? `**The AI was unavailable for ${unavailable} ticket(s)**; they are counted as wrong (the (none) column).`
      : 'The AI answered every ticket.',
    '',
    '- **Precision**: of the tickets the AI gave this label, how many really had it.',
    '- **Recall**: of the tickets that really had this label, how many the AI found.',
    '- **F1**: the balance of the two (1 is perfect).',
    "- **Cohen's kappa**: agreement with the hand labels after removing lucky guesses " +
      '(0 = chance, 1 = perfect; Landis & Koch bands).',
    '',
    section('Category', metrics.category),
    section('Priority (five levels)', metrics.priority),
    section('Priority level (P1-P4, Trivial counted as P4)', metrics.level),
  ].join('\n');
}

const CUTOFFS = [0.5, 0.6, 0.7, 0.8, 0.9, 0.95];

function sweepTable(rows, current) {
  return [
    '| Cut-off | Handed to a person | Right handoffs (AI was wrong) | Needless handoffs (AI was right) | Errors caught | Errors missed | Accuracy on the rest |',
    '| --- | --- | --- | --- | --- | --- | --- |',
    ...rows.map((r) => {
      const mark = r.cutoff === current ? ' **(used)**' : '';
      return (
        `| ${r.cutoff}${mark} | ${r.handedOff} (${pct(r.handedOffRate)}) | ${r.rightHandoffs} | ` +
        `${r.needlessHandoffs} | ${pct(r.errorsCaught)} | ${r.missedErrors} | ${pct(r.keptAccuracy)} |`
      );
    }),
  ].join('\n');
}

function handoffReport(results, generatedAt) {
  const limits = getThresholds();
  const withLevel = results.map((r) => ({ ...r, eitherCorrect: r.categoryCorrect && r.priorityCorrect }));
  const flagged = withLevel.filter((r) => r.humanCheckReasons.length > 0);
  const wrong = withLevel.filter((r) => !r.eitherCorrect);
  const flaggedWrong = flagged.filter((r) => !r.eitherCorrect).length;
  const kept = withLevel.filter((r) => r.humanCheckReasons.length === 0);
  const keptRight = kept.filter((r) => r.eitherCorrect).length;
  const reasonCounts = {};
  flagged.forEach((r) => r.humanCheckReasons.forEach((x) => {
    reasonCounts[x] = (reasonCounts[x] || 0) + 1;
  }));
  const noConfidence = results.filter((r) => r.priorityConfidence == null).length;

  return [
    '# "Needs human check" handoff: evaluation',
    '',
    `Generated by \`node scripts/ai/evaluate-classification.js\` on ${generatedAt}, ` +
      `model \`${getModelInfo().name}\`, ${results.length} hand-labelled tickets. Overwritten on every run.`,
    '',
    "Confidence is the probability the model gave the first token of its answer after " +
      '"Priority:" or "Category:". Below the cut-off the ticket is marked **Needs human ' +
      'check** instead of trusting the AI. A handoff is *right* when the AI had in fact got that ' +
      'field wrong, and *needless* when it was right.',
    '',
    noConfidence
      ? `**${noConfidence} ticket(s) had no confidence value** (provider gave no token probabilities); they are never handed off.`
      : 'Every ticket had a confidence value.',
    '',
    `## Result with the cut-offs in use (priority ${limits.priority}, category ${limits.category})`,
    '',
    '| | Tickets |',
    '| --- | --- |',
    `| Marked "Needs human check" | ${flagged.length} of ${results.length} (${pct(flagged.length / results.length)}) |`,
    `| ...where the AI really had the category or priority wrong | ${flaggedWrong} |`,
    `| ...where the AI was actually right (needless) | ${flagged.length - flaggedWrong} |`,
    `| Wrong tickets caught by the handoff | ${flaggedWrong} of ${wrong.length} |`,
    `| Accuracy on tickets the AI kept (both fields right) | ${kept.length ? pct(keptRight / kept.length) : '—'} (${keptRight}/${kept.length}) |`,
    `| Accuracy with no handoff at all | ${pct((results.length - wrong.length) / results.length)} |`,
    '',
    'Reasons:',
    '',
    ...Object.entries(reasonCounts).map(([reason, count]) => `- ${reason}: ${count}`),
    ...(Object.keys(reasonCounts).length ? [] : ['- none']),
    '',
    '## Priority: handoff at each cut-off',
    '',
    sweepTable(handoffSweep(results, 'priorityConfidence', 'priorityCorrect', CUTOFFS), limits.priority),
    '',
    '## Category: handoff at each cut-off',
    '',
    sweepTable(handoffSweep(results, 'categoryConfidence', 'categoryCorrect', CUTOFFS), limits.category),
    '',
    '## Every ticket',
    '',
    '| # | Expected | AI said | Priority confidence | Category confidence | Handed off? | Why |',
    '| --- | --- | --- | --- | --- | --- | --- |',
    ...results.map(
      (r) =>
        `| ${r.id} | ${r.expectedCategory} / ${r.expectedPriority} | ${r.predictedCategory || '—'} / ${r.predictedPriority || '—'} | ` +
        `${r.priorityConfidence ?? '—'} | ${r.categoryConfidence ?? '—'} | ${r.humanCheckReasons.length ? 'yes' : 'no'} | ` +
        `${r.humanCheckReasons.join(', ') || ''} |`
    ),
    '',
  ].join('\n');
}

function printBreakdown(title, byValue) {
  console.log(`\n${title}`);

  for (const [value, { correct, total }] of Object.entries(byValue)) {
    const pct = ((correct / total) * 100).toFixed(1);
    console.log(`  ${value}: ${correct}/${total} (${pct}%)`);
  }
}

async function run() {
  const results = [];

  console.log(`Classifying ${testSet.length} tickets against the live AI service...\n`);

  for (const test of testSet) {
    const start = Date.now();
    const ai = await getAiSuggestions(test.description);
    const elapsed = Date.now() - start;

    const categoryCorrect = ai.category === test.expectedCategory;
    const priorityCorrect = ai.priority === test.expectedPriority;

    console.log(
      `[${test.id}/${testSet.length}] category=${ai.category || '(none)'} ` +
        `(expected ${test.expectedCategory}, ${categoryCorrect ? 'OK' : 'MISS'}) ` +
        `priority=${ai.priority || '(none)'} (expected ${test.expectedPriority}, ` +
        `${priorityCorrect ? 'OK' : 'MISS'}) (${elapsed}ms)`
    );

    results.push({
      id: test.id,
      description: test.description,
      expectedCategory: test.expectedCategory,
      expectedPriority: test.expectedPriority,
      predictedCategory: ai.category,
      predictedPriority: ai.priority,
      expectedLevel: priorityLevel(test.expectedPriority),
      predictedLevel: priorityLevel(ai.priority),
      categoryCorrect,
      priorityCorrect,
      levelCorrect: priorityLevel(ai.priority) === priorityLevel(test.expectedPriority),
      aiUnavailable: ai.category === null,
      categoryConfidence: ai.categoryConfidence ?? null,
      priorityConfidence: ai.priorityConfidence ?? null,
      humanCheckReasons: humanCheckReasons(ai),
      ms: elapsed,
    });
  }

  const categoryAccuracy = results.filter((r) => r.categoryCorrect).length / results.length;
  const priorityAccuracy = results.filter((r) => r.priorityCorrect).length / results.length;
  const unavailableCount = results.filter((r) => r.aiUnavailable).length;

  console.log('\n=== Overall ===');
  console.log(`Category accuracy: ${(categoryAccuracy * 100).toFixed(1)}% (${results.filter((r) => r.categoryCorrect).length}/${results.length})`);
  console.log(`Priority accuracy: ${(priorityAccuracy * 100).toFixed(1)}% (${results.filter((r) => r.priorityCorrect).length}/${results.length})`);

  if (unavailableCount > 0) {
    console.log(`AI unavailable (fell back to defaults) on ${unavailableCount}/${results.length} tickets.`);
  }

  printBreakdown('=== Category accuracy by expected category ===', summariseByField(results, 'category', 'expectedCategory'));
  printBreakdown('=== Priority accuracy by expected priority ===', summariseByField(results, 'priority', 'expectedPriority'));

  console.log('\n=== Category confusion (expected -> predicted) ===');
  for (const [pair, count] of confusionPairs(results, 'expectedCategory', 'predictedCategory')) {
    console.log(`  ${pair}: ${count}`);
  }

  console.log('\n=== Priority confusion (expected -> predicted) ===');
  for (const [pair, count] of confusionPairs(results, 'expectedPriority', 'predictedPriority')) {
    console.log(`  ${pair}: ${count}`);
  }

  // Priorities from most to least urgent, so the matrix reads naturally.
  const priorityOrder = [...PRIORITIES].reverse();
  const metrics = {
    category: evaluateField(results, 'expectedCategory', 'predictedCategory', CATEGORIES),
    priority: evaluateField(results, 'expectedPriority', 'predictedPriority', priorityOrder),
    level: evaluateField(results, 'expectedLevel', 'predictedLevel', LEVELS),
  };

  for (const [name, m] of Object.entries(metrics)) {
    console.log(
      `\n${name}: accuracy ${pct(m.accuracy)}, macro F1 ${m.macro.f1}, ` +
        `kappa ${m.kappa} (${m.kappaStrength})`
    );
  }

  const generatedAt = new Date().toISOString();
  const handoffPath = path.join(__dirname, '..', '..', 'docs', 'ai-handoff-evaluation.md');
  fs.writeFileSync(handoffPath, handoffReport(results, generatedAt));
  console.log('Written: docs/ai-handoff-evaluation.md');
  const mdPath = path.join(__dirname, '..', '..', 'docs', 'ai-classification-metrics.md');
  fs.writeFileSync(mdPath, metricsReport(metrics, results, generatedAt));
  console.log('Written: docs/ai-classification-metrics.md');

  const output = {
    generatedAt,
    model: getModelInfo().name,
    metrics,
    categoryAccuracy: Number((categoryAccuracy * 100).toFixed(1)),
    priorityAccuracy: Number((priorityAccuracy * 100).toFixed(1)),
    total: results.length,
    aiUnavailableCount: unavailableCount,
    results,
  };

  const outPath = path.join(__dirname, '..', '..', 'docs', 'ai-classification-evaluation-raw.json');
  fs.writeFileSync(outPath, JSON.stringify(output, null, 2));

  console.log(`\nWritten: docs/ai-classification-evaluation-raw.json`);
}

run().catch((error) => {
  console.error('\nEvaluation failed:', error.message, '\n');
  process.exitCode = 1;
});
