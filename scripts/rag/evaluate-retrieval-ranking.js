/*
 * Knowledge-base search ranking evaluation: Hit@1, Hit@3, Hit@5 and MRR.
 *
 *   node scripts/rag/evaluate-retrieval-ranking.js
 *
 * Uses every labelled in-scope question we have (tests/rag/testset.json
 * plus the questions in tests/rag/answer-evaluation-set.json that have an
 * expected article, without duplicates). For each question it ranks the
 * knowledge-base ARTICLES (not chunks: an article's rank is the rank of
 * its best chunk) and records where the correct article came.
 *
 * Two searches are compared:
 *   - embedding search, exactly as the AI assistant runs it
 *     (retrievalService.retrieve), and
 *   - the app's keyword search (knowledgeBaseService.searchArticles), as
 *     a baseline.
 *
 * Out-of-scope questions have no correct article, so they can't be scored
 * this way; they are covered by the threshold check in rag-evaluation.md.
 *
 * Writes docs/rag-retrieval-ranking.md (overwritten on every run).
 */

require('dotenv').config({ quiet: true });

const fs = require('fs');
const path = require('path');

const db = require('../../src/models');
const { retrieve } = require('../../src/services/rag/retrievalService');
const { getModelInfo } = require('../../src/services/rag/embeddingService');
const { searchArticles, loadArticles } = require('../../src/services/knowledgeBaseService');
const { rankOf, summarise } = require('./rankingStats');

const retrievalSet = require('../../tests/rag/testset.json');
const answerSet = require('../../tests/rag/answer-evaluation-set.json');

function buildQuestionSet() {
  const seen = new Map();

  for (const item of retrievalSet) {
    if (item.expectedArticleId == null) continue;
    seen.set(item.question.toLowerCase(), {
      question: item.question,
      expectedArticleId: item.expectedArticleId,
      type: item.type,
      source: 'testset',
    });
  }

  for (const item of answerSet) {
    if (item.expectedArticleId == null) continue;
    const key = item.question.toLowerCase();
    const existing = seen.get(key);
    if (existing) {
      if (Number(existing.expectedArticleId) !== Number(item.expectedArticleId)) {
        throw new Error(`The two test sets disagree on the article for "${item.question}".`);
      }
      continue;
    }
    seen.set(key, {
      question: item.question,
      expectedArticleId: item.expectedArticleId,
      type: 'realistic',
      source: 'answer-set',
    });
  }

  return [...seen.values()];
}

// Every article, best first, from the embedding search.
async function embeddingRanking(question) {
  const result = await retrieve(question, {
    topK: 10000,
    threshold: null,
    maxPerArticle: 1,
    relativeCutoff: 0,
  });
  return {
    ids: result.matches.map((m) => m.articleId),
    topScore: result.topScore,
  };
}

function keywordRanking(question) {
  return { ids: searchArticles(question).map((a) => a.id) };
}

const pct = (n) => `${(n * 100).toFixed(1)}%`;
const f = (n) => n.toFixed(3);

function summaryRow(name, s) {
  return `| ${name} | ${s.questions} | ${pct(s.hitAt1)} | ${pct(s.hitAt3)} | ${pct(s.hitAt5)} | ${f(s.mrr)} | ${s.notFound} |`;
}

async function run() {
  const questions = buildQuestionSet();
  const titles = new Map(loadArticles().map((a) => [Number(a.id), a.title]));
  console.log(`Ranking ${questions.length} labelled questions with ${getModelInfo().name}...`);

  const rows = [];
  for (const q of questions) {
    const emb = await embeddingRanking(q.question);
    const kw = keywordRanking(q.question);
    rows.push({
      ...q,
      embeddingRank: rankOf(emb.ids, q.expectedArticleId),
      embeddingTop: emb.ids[0],
      topScore: emb.topScore,
      keywordRank: rankOf(kw.ids, q.expectedArticleId),
      keywordTop: kw.ids[0] ?? null,
    });
  }

  const embedding = summarise(rows.map((r) => r.embeddingRank));
  const keyword = summarise(rows.map((r) => r.keywordRank));

  const types = [...new Set(rows.map((r) => r.type))];
  const byType = types.map((type) => ({
    type,
    s: summarise(rows.filter((r) => r.type === type).map((r) => r.embeddingRank)),
  }));

  console.log(`Embedding: Hit@1 ${pct(embedding.hitAt1)}, Hit@3 ${pct(embedding.hitAt3)}, MRR ${f(embedding.mrr)}`);
  console.log(`Keyword:   Hit@1 ${pct(keyword.hitAt1)}, Hit@3 ${pct(keyword.hitAt3)}, MRR ${f(keyword.mrr)}`);

  const misses = rows.filter((r) => r.embeddingRank !== 1);

  const md = [
    '# Knowledge-base search: ranking evaluation',
    '',
    `Generated by \`node scripts/rag/evaluate-retrieval-ranking.js\` on ${new Date().toISOString()} ` +
      `with \`${getModelInfo().name}\`. Overwritten on every run.`,
    '',
    `${questions.length} labelled in-scope questions: every question in tests/rag/testset.json ` +
      'and tests/rag/answer-evaluation-set.json that has a correct article, without duplicates. ' +
      'Out-of-scope questions have no correct article, so they are not scored here ' +
      '(see [rag-evaluation.md](./rag-evaluation.md) for how they are refused).',
    '',
    'Articles are ranked by their best-matching chunk.',
    '',
    '- **Hit@1**: the correct article came first.',
    '- **Hit@3 / Hit@5**: it was in the top 3 / top 5. The assistant reads the top few chunks, so Hit@3 is the one that matters most for answers.',
    '- **MRR** (mean reciprocal rank): 1 for first place, 0.5 for second, 0.33 for third, 0 if not found, averaged. 1.0 is perfect.',
    '',
    '## Results',
    '',
    '| Search | Questions | Hit@1 | Hit@3 | Hit@5 | MRR | Not found |',
    '| --- | --- | --- | --- | --- | --- | --- |',
    summaryRow('**Embedding search (used by the assistant)**', embedding),
    summaryRow('Keyword search (baseline)', keyword),
    '',
    'The keyword search only returns articles that share enough words with the question, ' +
      'so a question worded differently from the article often gets nothing ("not found").',
    '',
    '## Embedding search by question type',
    '',
    '| Type | Questions | Hit@1 | Hit@3 | Hit@5 | MRR | Not found |',
    '| --- | --- | --- | --- | --- | --- | --- |',
    ...byType.map(({ type, s }) => summaryRow(type, s)),
    '',
    '## Questions where the correct article was not first',
    '',
    ...(misses.length
      ? [
          '| Question | Correct article | Came | First instead | Keyword rank |',
          '| --- | --- | --- | --- | --- |',
          ...misses.map(
            (r) =>
              `| ${r.question} | ${titles.get(Number(r.expectedArticleId)) || r.expectedArticleId} | ` +
              `${r.embeddingRank ?? 'not found'} | ${titles.get(Number(r.embeddingTop)) || r.embeddingTop} | ` +
              `${r.keywordRank ?? 'not found'} |`
          ),
        ]
      : ['None: the correct article came first for every question.']),
    '',
    '## Every question',
    '',
    '| # | Type | Question | Embedding rank | Top score | Keyword rank |',
    '| --- | --- | --- | --- | --- | --- |',
    ...rows.map(
      (r, i) =>
        `| ${i + 1} | ${r.type} | ${r.question.replace(/\|/g, '/')} | ${r.embeddingRank ?? 'not found'} | ` +
        `${f(r.topScore)} | ${r.keywordRank ?? 'not found'} |`
    ),
    '',
  ].join('\n');

  const out = path.join(__dirname, '..', '..', 'docs', 'rag-retrieval-ranking.md');
  fs.writeFileSync(out, md);
  console.log('Written: docs/rag-retrieval-ranking.md');
}

run()
  .catch((error) => {
    console.error('Evaluation failed:', error.message);
    process.exitCode = 1;
  })
  .finally(() => db.sequelize.close());
